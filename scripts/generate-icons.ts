/**
 * Regenerates src/generated/icons.ts from @primer/octicons and simple-icons.
 *
 * Both packages stay devDependencies. The octicon runtime object carries a
 * parsed AST, keywords, and five size variants per icon — 1.1MB to serve a
 * path string — and simple-icons is a 4.4MB catalogue of which a badge about
 * a repository wants a couple of hundred. Stripping each to its path is what
 * makes the registry worth shipping, so it is generated rather than imported.
 *
 * Octicons come in whole. The simple-icons are the curated list in
 * ./simple-icon-slugs.ts, and a slug an octicon already answers to is left
 * out: the two share one namespace, and the octicon is the one callers have
 * always had.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import octicons from '@primer/octicons'
import { minBy } from 'es-toolkit'

import { SIMPLE_ICON_SLUGS } from './simple-icon-slugs.ts'

const OUT = 'src/generated/icons.ts'

/** An icon's smallest variant, which the renderer scales to whatever it needs. */
const smallestVariant = (
  heights: Record<string, { width: number; path: string }>
) => {
  // every octicon ships a 16px variant, and it carries the least path data of
  // any of them; minBy is only a guard for one that somehow does not
  const key = '16' in heights ? '16' : minBy(Object.keys(heights), Number)
  if (!key) {
    throw new Error('octicon has no size variants')
  }
  return { height: Number(key), ...heights[key] }
}

type Icon = { path: string; width: number; height: number }

const octicon = Object.fromEntries(
  Object.entries(octicons).map(([slug, icon]): [string, Icon] => {
    const { path, width, height } = smallestVariant(icon.heights)
    return [slug, { path, width, height }]
  })
)

/** Every simple-icons mark is one path on a 24x24 square. */
const SIMPLE_ICON_BOX = 24

// resolved from the package's own entry point, since it exports nothing else
// to resolve against and a node_modules path differs between installers
const iconsDir = join(
  dirname(createRequire(import.meta.url).resolve('simple-icons')),
  'icons'
)

const simpleIcon = Object.fromEntries(
  SIMPLE_ICON_SLUGS.filter((slug) => {
    // the octicon wins the name, and says so rather than disappearing quietly
    const taken = slug in octicon
    if (taken) {
      console.log(`  skipping "${slug}": an octicon already answers to it`)
    }
    return !taken
  }).map((slug): [string, Icon] => {
    // read from the package's own SVGs rather than its runtime object, which
    // would need a namespace import to look a slug up by name
    const svg = readFileSync(join(iconsDir, `${slug}.svg`), 'utf8')
    const path = svg.match(/<path d="([^"]*)"/)?.[1]
    if (!path) {
      throw new Error(`simple-icons has no single-path mark for "${slug}"`)
    }
    return [
      slug,
      {
        path: `<path d="${path}"></path>`,
        width: SIMPLE_ICON_BOX,
        height: SIMPLE_ICON_BOX,
      },
    ]
  })
)

const entries = Object.entries({ ...octicon, ...simpleIcon })
  .sort(([a], [b]) => a.localeCompare(b))
  // JSON.stringify, not hand-escaping: two octicons carry newlines in their
  // path markup, which no amount of quote-escaping survives
  .map(
    ([slug, { path, width, height }]) =>
      `  ${JSON.stringify(slug)}: [${JSON.stringify(path)}, ${width}, ${height}],`
  )

const file = `// GENERATED by scripts/generate-icons.ts — run \`pnpm gen:icons\` to refresh.
// Every octicon, plus the simple-icons listed in scripts/simple-icon-slugs.ts,
// as [path markup, viewBox width, viewBox height].
export const ICONS: Record<
  string,
  [path: string, width: number, height: number]
> = {
${entries.join('\n')}
}
`

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
writeFileSync(join(root, OUT), file)
console.log(
  `${OUT}: ${entries.length} icons — ${Object.keys(octicon).length} octicons, ${Object.keys(simpleIcon).length} simple-icons`
)
