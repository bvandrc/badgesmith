/**
 * Regenerates src/icons.generated.ts from @primer/octicons.
 *
 * The package itself stays a devDependency: its runtime object carries a
 * parsed AST, keywords, and five size variants per icon — 1.1MB to serve a
 * path string. Stripping it to the smallest variant's path costs 56KB gzipped
 * for all of them, so the registry is generated rather than imported.
 */

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import octicons from '@primer/octicons'
import { minBy } from 'es-toolkit'

const OUT = 'src/icons.generated.ts'

/** An icon's smallest variant, which the renderer scales to whatever it needs. */
const smallestVariant = (
  heights: Record<string, { width: number; path: string }>
) => {
  // every octicon ships a 16px variant, and it carries the least path data of
  // any of them; minBy is only a guard for one that somehow does not
  const key = '16' in heights ? '16' : minBy(Object.keys(heights), Number)
  if (!key) {
    throw new Error('octicon has no size variants')
  }
  return { height: Number(key), ...heights[key] }
}

const entries = Object.entries(octicons)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, icon]) => {
    const { path, width, height } = smallestVariant(icon.heights)
    // JSON.stringify, not hand-escaping: two octicons carry newlines in their
    // path markup, which no amount of quote-escaping survives
    return `  ${JSON.stringify(slug)}: [${JSON.stringify(path)}, ${width}, ${height}],`
  })

const file = `// GENERATED by scripts/generate-icons.ts — run \`pnpm gen:icons\` to refresh.
// Every octicon as [path markup, viewBox width, viewBox height].
export const ICONS: Record<
  string,
  [path: string, width: number, height: number]
> = {
${entries.join('\n')}
}
`

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
writeFileSync(join(root, OUT), file)
console.log(`${OUT}: ${entries.length} icons`)
