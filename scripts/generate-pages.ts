/**
 * Regenerates README.md and the landing page the worker serves, from the
 * components under site/.
 *
 * The page is rendered here rather than in the worker, so Preact stays a
 * devDependency and the runtime serves a string.
 */
import { writeFileSync } from 'node:fs'
import { render } from 'preact-render-to-string'

import { readme } from '../site/readme.tsx'
import { UsagePage } from '../site/UsagePage.tsx'

const write = (path: string, content: string) =>
  writeFileSync(new URL(`../${path}`, import.meta.url), content)

write('README.md', readme)

const html = `<!doctype html>\n${render(UsagePage())}\n`
write(
  'src/generated/usage-page.ts',
  `// GENERATED by scripts/generate-pages.ts — run \`pnpm gen:pages\` to refresh.
// site/UsagePage.tsx, rendered to the string the worker serves.

/** The landing page, served on a bare root. */
export const USAGE_PAGE = ${JSON.stringify(html)}
`
)
